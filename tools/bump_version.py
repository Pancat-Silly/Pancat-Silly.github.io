"""Site version: bumped on every commit by the pre-commit hook (tools/hooks/pre-commit, enabled with
`git config core.hooksPath tools/hooks`). Run by hand: python3 tools/bump_version.py

  version.json        {"ver": "2026.11.19-2"}  polled by open pages -> "새 버전이 나왔어요" notice (SITE.watchVer)
  js/data/version.js  const SITE_VER = '...';  the version this page was loaded with (shown in both games)
  index.html          every css/js URL gets ?v=<ver>, so a refresh really fetches the new files (Pages caches 10 min)
"""
import os, re, json, datetime
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = lambda *a: os.path.join(R, *a)
try: old = json.load(open(P('version.json'), encoding='utf-8')).get('ver', '')
except Exception: old = ''
day = datetime.date.today().strftime('%Y.%m.%d')
n = int(old.split('-')[1]) + 1 if old.startswith(day + '-') else 1
ver = '%s-%d' % (day, n)
open(P('version.json'), 'w', encoding='utf-8', newline='\n').write(json.dumps({'ver': ver}) + '\n')
open(P('js', 'data', 'version.js'), 'w', encoding='utf-8', newline='\n').write("// generated by tools/bump_version.py (pre-commit hook)\nconst SITE_VER = '%s';\n" % ver)
h = open(P('index.html'), encoding='utf-8').read()
h = re.sub(r'(<script src="|<link rel="stylesheet" href=")((?:js|css)/[^"?]+)(?:\?v=[^"]*)?"', lambda m: '%s%s?v=%s"' % (m.group(1), m.group(2), ver), h)
open(P('index.html'), 'w', encoding='utf-8', newline='').write(h)
print('site version', ver)
