"""Built-in jobs made with the dev tool (result txt files in tools/modjobs/): code + sounds -> js/data/jobs_builtin.js.
Run from anywhere: python3 tools/mkmodjobs.py   (needs ffmpeg)
They load through the mod API (APVP.addJob) at boot, exactly as tested in the dev tool."""
import re, json, base64, subprocess, sys, os, tempfile
T = os.path.dirname(os.path.abspath(__file__)); R = os.path.dirname(T); out = []
for f in sorted(os.listdir(os.path.join(T, 'modjobs'))):
    if not f.endswith('.txt'): continue
    t = open(os.path.join(T, 'modjobs', f), encoding='utf-8').read()
    code = re.search(r'=====JS 코드=====\s*```js\n(.*?)\n```', t, re.S).group(1)
    snd = {}
    sec = t.split('=====효과음=====')[1] if '=====효과음=====' in t else ''
    for m in re.finditer(r'^([^\s:]+)\s*:\s*data:audio/([a-z0-9]+);base64,([A-Za-z0-9+/=]+)', t, re.M):
        name, ext, b64 = m.groups(); raw = base64.b64decode(b64)
        with tempfile.TemporaryDirectory() as d:
            src = os.path.join(d, 'in.' + ext); dst = os.path.join(d, 'out.mp3'); open(src, 'wb').write(raw)
            subprocess.run(['ffmpeg', '-hide_banner', '-loglevel', 'error', '-y', '-i', src, '-af', 'silenceremove=start_periods=1:start_threshold=-50dB', '-c:a', 'libmp3lame', '-b:a', '96k', dst], check=True)
            snd[name] = 'data:audio/mpeg;base64,' + base64.b64encode(open(dst, 'rb').read()).decode()
    out.append({'file': f, 'code': code, 'snd': snd})
    print(f, len(code), list(snd), file=sys.stderr)
open(os.path.join(R, 'js', 'data', 'jobs_builtin.js'), 'w', encoding='utf-8').write('// generated by mkmodjobs.py (dev-tool result files in tools/modjobs/)\nconst BUILTIN_JOBS=' + json.dumps(out, ensure_ascii=False) + ';\n')
