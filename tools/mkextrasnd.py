"""Extra 4중인격 sounds added after the original map package (apvp_assets.js can't be rebuilt without it).
  tools/sounds/<name>.(wav|mp3|ogg) -> js/data/apvp_extra_snd.js   (needs ffmpeg)
The file adds its sounds to SOUNDS, so they play with G.sound('<name>', ...) like the built-in ones.
  python3 tools/mkextrasnd.py"""
import os, base64, subprocess, tempfile, json
T = os.path.dirname(os.path.abspath(__file__)); R = os.path.dirname(T); D = os.path.join(T, 'sounds'); out = {}
for f in sorted(os.listdir(D)):
    name, ext = os.path.splitext(f)
    if ext.lower() not in ('.wav', '.mp3', '.ogg', '.m4a'): continue
    with tempfile.TemporaryDirectory() as d:
        dst = os.path.join(d, 'o.mp3')
        subprocess.run(['ffmpeg', '-hide_banner', '-loglevel', 'error', '-y', '-i', os.path.join(D, f), '-af', 'silenceremove=start_periods=1:start_threshold=-50dB', '-ac', '1', '-c:a', 'libmp3lame', '-b:a', '96k', dst], check=True)
        out[name] = base64.b64encode(open(dst, 'rb').read()).decode()
    print(name, len(out[name]))
open(os.path.join(R, 'js', 'data', 'apvp_extra_snd.js'), 'w', encoding='utf-8', newline='\n').write('// generated by tools/mkextrasnd.py (tools/sounds/*)\nObject.assign(SOUNDS, ' + json.dumps(out) + ');\n')
